import type { AttackKey, Pose, WeaponMoves } from './types';

/*
 * The zweihander: right hand at the guard, left at the pommel, left foot forward.
 *
 * A three-part combo. A long cut from high right to low left, a rising return from low left to high
 * right on a passing step, and a lunging thrust out of the shoulder. Each attack ends in the pose the next
 * one starts from. The blade has two edges, so the rising cut leads with the false edge and the wrists
 * never have to turn over.
 *
 * Every strike runs the same way: one easeIn out of the hold, then linear segments that each go a little
 * faster, so that the tip is at its fastest on the impact key. Linear segments that each go slower carry it
 * past and let it run down, and the pose keeps sagging after that instead of freezing. An easeOut would
 * spend nearly all of its travel in the first third and then sit still. easeIn ends at three times its
 * average speed, which is what the first linear segment has to match.
 *
 * The character does not travel while the keys play, so each lunge is drawn by the keys: both hips and front
 * foot go a long way out from the origin, and that is paid back with lifted steps through the recovery.
 * Above about 0.15 of lift the whole foot is clear of the floor, so that is what a step needs.
 */

