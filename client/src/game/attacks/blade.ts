/*
 * Blades: quick, clean and committed. Each attack in a list starts where the one before it ended, so
 * they read as one combo: down from the right shoulder, back across from the left, then a finisher.
 * The hips start each strike before the shoulders, the front foot lands as the blade arrives, and the
 * edge faces the way the tip is travelling.
 *
 * Every attack has the same beats. A single wind-up, a held peak where the hips start while the blade
 * waits, a strike spread over about five frames, a follow-through that drags the body round, and a slow
 * recovery. Pass-through keys are linear because any other ease stops the blade at the key. The last key
 * is an easeOut that travels only a little: it starts at three times its average speed, so it has to be
 * short enough for that to match the speed coming in, or the recovery twitches.
 */

